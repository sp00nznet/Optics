import { useEffect, useState } from 'react'
import { Code, Copy, Check } from 'lucide-react'
import { STLLoader } from 'three/examples/jsm/loaders/STLLoader.js'
import * as THREE from 'three'

interface ScadViewerProps {
  fileUrl: string
  fileName: string
  fileType: string
  className?: string
}

export default function ScadViewer({ fileUrl, fileName, fileType, className = '' }: ScadViewerProps) {
  const [code, setCode] = useState<string>('')
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    setLoading(true)
    setError(null)

    if (fileType.toLowerCase() === 'scad') {
      // Load actual SCAD file content
      fetch(fileUrl)
        .then((response) => {
          if (!response.ok) throw new Error('Failed to load file')
          return response.text()
        })
        .then((text) => {
          setCode(text)
          setLoading(false)
        })
        .catch((err) => {
          setError(err.message)
          setLoading(false)
        })
    } else if (fileType.toLowerCase() === 'stl') {
      // Parse STL and convert to OpenSCAD polyhedron
      const loader = new STLLoader()
      loader.load(
        fileUrl,
        (geometry) => {
          const scadCode = convertGeometryToScad(geometry, fileName)
          setCode(scadCode)
          setLoading(false)
        },
        undefined,
        () => {
          setError('Failed to parse STL file')
          setLoading(false)
        }
      )
    } else {
      // Other file types - show import instruction
      const scadCode = generateScadImport(fileName, fileType)
      setCode(scadCode)
      setLoading(false)
    }
  }, [fileUrl, fileName, fileType])

  const copyToClipboard = () => {
    navigator.clipboard.writeText(code)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  if (loading) {
    return (
      <div className={`flex items-center justify-center bg-gray-900 rounded-lg ${className}`}>
        <div className="text-gray-400">Loading...</div>
      </div>
    )
  }

  if (error) {
    return (
      <div className={`flex items-center justify-center bg-gray-900 rounded-lg ${className}`}>
        <div className="text-red-400">{error}</div>
      </div>
    )
  }

  return (
    <div className={`bg-gray-900 rounded-lg overflow-hidden flex flex-col ${className}`}>
      <div className="flex items-center justify-between px-4 py-2 bg-gray-800 border-b border-gray-700">
        <div className="flex items-center gap-2">
          <Code className="w-4 h-4 text-gray-400" />
          <span className="text-sm text-gray-300">
            {fileType.toLowerCase() === 'scad' ? 'OpenSCAD Source' : 'OpenSCAD Import'}
          </span>
        </div>
        <button
          onClick={copyToClipboard}
          className="flex items-center gap-1 px-2 py-1 text-xs text-gray-400 hover:text-white transition-colors"
        >
          {copied ? <Check className="w-3 h-3" /> : <Copy className="w-3 h-3" />}
          {copied ? 'Copied!' : 'Copy'}
        </button>
      </div>
      <pre className="p-4 overflow-auto flex-1 text-sm" style={{ maxHeight: 'calc(100% - 40px)' }}>
        <code className="text-green-400 font-mono whitespace-pre">{code}</code>
      </pre>
    </div>
  )
}

function convertGeometryToScad(geometry: THREE.BufferGeometry, fileName: string): string {
  const positions = geometry.getAttribute('position')
  const baseName = fileName.replace(/\.[^/.]+$/, '')
  const moduleName = sanitizeModuleName(baseName)

  // Build unique vertices list and face indices
  const vertices: number[][] = []
  const vertexMap = new Map<string, number>()
  const faces: number[][] = []

  const getVertexIndex = (x: number, y: number, z: number): number => {
    // Round to avoid floating point precision issues
    const key = `${x.toFixed(6)},${y.toFixed(6)},${z.toFixed(6)}`
    if (vertexMap.has(key)) {
      return vertexMap.get(key)!
    }
    const index = vertices.length
    vertices.push([x, y, z])
    vertexMap.set(key, index)
    return index
  }

  // Process triangles
  for (let i = 0; i < positions.count; i += 3) {
    const v0 = getVertexIndex(
      positions.getX(i),
      positions.getY(i),
      positions.getZ(i)
    )
    const v1 = getVertexIndex(
      positions.getX(i + 1),
      positions.getY(i + 1),
      positions.getZ(i + 1)
    )
    const v2 = getVertexIndex(
      positions.getX(i + 2),
      positions.getY(i + 2),
      positions.getZ(i + 2)
    )
    faces.push([v0, v1, v2])
  }

  // Generate OpenSCAD code
  let scad = `// OpenSCAD polyhedron generated from: ${fileName}
// Vertices: ${vertices.length}, Faces: ${faces.length}
// Generated by Optics 3D Model Library

module ${moduleName}() {
    polyhedron(
        points = [
`

  // Add vertices
  vertices.forEach((v, i) => {
    const comma = i < vertices.length - 1 ? ',' : ''
    scad += `            [${v[0].toFixed(6)}, ${v[1].toFixed(6)}, ${v[2].toFixed(6)}]${comma}\n`
  })

  scad += `        ],
        faces = [
`

  // Add faces
  faces.forEach((f, i) => {
    const comma = i < faces.length - 1 ? ',' : ''
    scad += `            [${f[0]}, ${f[1]}, ${f[2]}]${comma}\n`
  })

  scad += `        ],
        convexity = 10
    );
}

// Render the model
${moduleName}();
`

  return scad
}

function generateScadImport(fileName: string, fileType: string): string {
  const ext = fileType.toLowerCase()

  if (ext === 'obj') {
    return `// OpenSCAD import for: ${fileName}
// Note: OBJ support requires OpenSCAD 2019.05 or later

import("${fileName}");

// With convexity for complex models:
// import("${fileName}", convexity=10);
`
  } else if (ext === '3mf') {
    return `// OpenSCAD import for: ${fileName}
// Note: 3MF support requires OpenSCAD 2019.05 or later

import("${fileName}");
`
  } else {
    return `// File: ${fileName}
// Type: ${fileType.toUpperCase()}

// This file type may not be directly importable in OpenSCAD.
// Consider converting to STL format first.
`
  }
}

function sanitizeModuleName(name: string): string {
  // Convert to valid OpenSCAD module name
  return name
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .replace(/^[0-9]/, '_$&')
    .toLowerCase()
}
